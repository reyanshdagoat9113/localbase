import type { ColumnSchema } from "@localbase/shared";
import type { SqlDialect } from "./types.js";

/**
 * PostgreSQL expression that produces an ISO-8601 UTC millisecond timestamp
 * string (`YYYY-MM-DDTHH:MM:SS.mmmZ`), matching SQLite's
 * `(strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))` and `Date.prototype.toISOString()`.
 */
const PG_ISO_UTC_NOW =
  `(to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`;

export const postgresDialect: SqlDialect = {
  engine: "postgres",

  placeholder(index: number): string {
    return `$${index}`;
  },

  columnType(col: ColumnSchema): string {
    switch (col.type) {
      case "integer":
        return "INTEGER";
      case "text":
        return "TEXT";
      case "real":
        return "DOUBLE PRECISION";
      case "blob":
        return "BYTEA";
      case "boolean":
        return "BOOLEAN";
    }
  },

  autoIncrementPrimaryKey(col: ColumnSchema): string {
    return `${this.columnType(col)} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
  },

  normalizeDefault(col: ColumnSchema): string | undefined {
    if (col.default === undefined) return undefined;
    const trimmed = col.default.trim();
    if (col.type === "boolean") {
      const lower = trimmed.toLowerCase();
      if (lower === "true" || lower === "1") return "TRUE";
      if (lower === "false" || lower === "0") return "FALSE";
    }
    if (col.type === "text" && trimmed.toUpperCase() === "CURRENT_TIMESTAMP") {
      return PG_ISO_UTC_NOW;
    }
    return col.default;
  },

  encodeBoolean(value: boolean): boolean {
    return value;
  },

  migrationsTableDDL(tableName: string): string {
    return `
      CREATE TABLE IF NOT EXISTS "${tableName}" (
        "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "name" TEXT NOT NULL UNIQUE,
        "applied_at" TEXT NOT NULL DEFAULT ${PG_ISO_UTC_NOW}
      );
    `;
  },
};
